/* Includes ------------------------------------------------------------------*/
#include "main.h"
#include "app_clock.h"
#include "app_io.h"
#include "app_swd.h"

/* Private define ------------------------------------------------------------*/
#define APP_HEARTBEAT_PERIOD_MS (500U)

/**
  * @brief  Main program.
  * @retval int
  */
int main(void)
{
  /* Reset of all peripherals, Initializes the Systick. */
  HAL_Init();

  /* System clock configuration */
  APP_ClockInit();

  /* Board I/O: LED now; display, buttons, ADC, motor and valve drivers */
  APP_IO_Init();

  /* Keep PB6 (SWDIO) and PA2 (SWCLK) available for a while, then use them as
     I2C1 SDA/SCL if nothing is driving the debug interface. */
  APP_SwdHandover();

  /* infinite loop */
  while (1)
  {
    APP_IO_ToggleLed();
    HAL_Delay(APP_HEARTBEAT_PERIOD_MS);
  }
}

